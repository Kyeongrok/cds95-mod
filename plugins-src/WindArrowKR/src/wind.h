// 지금 함대가 받는 바람과 해류. 게임이 항해 화면 왼쪽 위에 글자로 쓰는 그 값이다
// ("풍향: 서 /풍속: 4"). [[16.분석-풍향·풍속·해류]]
//
// 표(0x4CB290 등)를 우리가 다시 읽지 않는 이유: 게임은 표값을 그대로 쓰지 않는다.
// 발짝마다 풍향을 ±1 흔들어 상태에 넣어 둔다(0x424E50). 그러니 표를 읽으면 화면 글자와
// 한 눈금씩 어긋난다. 상태를 그대로 읽는 쪽이 맞다.

typedef struct {
    int dir;      // 방위 0~15. 불어가는 쪽이다(기상학의 "북풍"과 반대)
    int speed;    // 세기. 바람 1~6, 해류 0~7
} Flow;

