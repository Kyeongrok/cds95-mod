// 함대 스프라이트 — 게임 해상 화면이 내 함대를 그릴 때 쓰는 그 그림이다.
//
// 고르는 규칙은 게임 렌더러 0x48A1E0 에서 그대로 읽었다(0x48A82E~0x48A8A4).
//
//   정박/육상 플래그  [0x5B61B4]   0 이면 항해 중
//   방향             [0x5B63C8]   16방향
//
//   항해 중: 배 아틀라스 0x5D68C8
//       함선종류 = 0x44C6E0(기함)        ; 기함은 0x473CD0/0x473DC0 으로 잡는다
//       클래스   = [0x5695D8 + 종류*4]   ; 8선종 -> 그림 4벌
//       프레임   = 클래스*8 + 방향/2     ; 16방향을 8방향으로 접는다
//
//   그 밖(육상·정박): 말 아틀라스 0x6092D0
//       프레임 = ((방향+1) 를 0~15 로 자른 값)/4*8 + [0x569550]
//
//   한 장은 48x48 팔레트 색인이고 색인 0 이 투명이다(2304바이트).
//   색은 ocean_palette.h 와 같은 표를 쓴다 — 같은 화면에 같이 그려지는 그림이라 당연하다.

#define SPR_W    48
