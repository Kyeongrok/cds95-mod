// 자리와 규칙은 전부 게임 코드를 읽어 확정했다(0x480CC0 BuildSaleList 계열).
//
//   도시 struct   모듈 + 0x1863A8 + id*92
//     +0x04 상태 비트  +0x0C 시세  +0x10 특산품 종류  +0x14 특산품 기준가  +0x18 특산품 재고
//     +0x40 도시상태  +0x44~0x54 공통 교역품 재고 다섯 칸  +0x58 문화권
//     ★ +0x44 다섯 칸이 지역 표(0x0DF0E0) 순서와 그대로 짝인 것이 아니다.
//       그 도시 특산품과 같은 종류는 지역 표에서 빠지고 자리도 안 차지한다(게임 0x42A160).
//       캘리컷은 표가 [후추 · 면화 · 면직물 · 편사] 인데 특산품이 후추라 자리가
//       면화 0 · 면직물 1 · 편사 2 로 당겨진다. 게임이 종류로 자리를 되찾는 함수가 0x42A0B0 이다.
//     ★ 특산품이 "지금 팔리는가" 도 게임 규칙이 있다(0x42A030) —
//       +0x04 의 bit0 이 켜져 있고 bit2 는 꺼져 있어야 하고, 판매 게이트도 지나야 한다.
//       이 판정이 어긋나면 위의 자리 계산까지 통째로 밀린다.
//   도시 record   모듈 + 0x0D14B0 + id*136
//     +0x10 · +0x14 = 연결 내륙도시 id(-1 없음)   +0x1C = 교역품 지역(0~33)
//     (세비야 record 가 4=톨레도, 카디스가 6=코르도바 — 게임의 "○○산" 수입품이 여기서 온다)
//   지역 공통품   모듈 + 0x0DF0E0 + 지역*20  (i32 x5, -1 끝)
//   교역품 레코드 모듈 + 0x0DCBBC + 종류*136 (int 34칸)      ★ 70종
//     +0x00~0x6C 지역 기준가 28칸(지역 0~27)   ← 오래 "34지역 격자" 로 알던 자리다
//     +0x70 중량(한 개 무게)  +0x74 ?(대개 7)  +0x78 ?(0/1)
//     +0x7C 이름 문자열 포인터  +0x80 그림 번호  +0x84 ?(0/4/8 — 분류로 보인다)
//     ★ 단, 이름 · 그림은 한 칸 밀려 있다 — 칸 k 의 +0x7C 에 들어 있는 것은
//       교역품 k 가 아니라 k+1 의 이름이다. 살아 있는 값으로 확인:
//       칸 10 의 +0x70=8(돌소금 무게, 게임 화면 8)인데 +0x7C 는 "올리브유"(=11번),
//       칸 21 은 +0x70=15(총) · 이름 "대포", 칸 22 는 +0x70=20(대포) · 이름 "후추".
//       중량만 칸 번호와 맞는다. 교역품 k 의 이름은 +0x7C-136 자리다.
//       (이름 · 그림은 정적 표 kTradeGoods / GOOD_PIC_BASE 를 쓰므로 지금 동작에는 영향 없다.)
//       0x480890 이 분류를 [0x4DCBB8 + 종류*136] 에서 읽는 것도 이 어긋남과 같은 뿌리로 보인다.
//     중량은 게임 구입창의 "중량" 칸 그대로다(올리브유 8 · 총 15 · 모직물 3 · 견직물 3 대조).
//   판매 게이트   모듈 + 0x18BAB0 + 종류*4  (0 이면 그 교역품은 안 판다)
//   내 짐         모듈 + 0x1B397C + 칸*16   {종류, 갯수, 원산지, ?}
//                 ★ 함대 통틀어 여덟 칸이다 — 배마다 여덟 칸이 아니다.
//                 ★ 게임 코드로 확정했다(note/TradeSellListBuilder-0x481070.md).
//                   매각 목록 빌더 0x481070 → 0x4B5780(짐 8칸 훑기) → 0x4742B0(칸 하나 읽기).
//                   0x4742B0 은 `if (slot >= 8) return 0;` 뒤에 obj + slot*16 + 0x54 를 읽는다.
//                   obj = 플레이어·함대 전역 객체 0x5B3928 이므로 짐 배열 = 0x5B397C.
//                   칸 수 8 도 칸 크기 16 도 코드 상수다. 0x4742F0 이 같은 자리에 되쓴다.
//                 짐 배열은 저 객체의 +0x54 멤버라서 절대주소 0x5B397C 가 코드에 한 번도
//                 안 나온다 — 전수 스캔해도 xref 0건이다. 그래서 오래 짐작만 했던 자리다.
//                 예전에 "배*8 + 칸" 으로 128칸을 훑던 것이 뒤에 붙은 남의 배열을 짐으로 읽어
//                 없는 물건(밀 1 · 밀 4 · 어육 1)을 만들어 냈다.
//                 앞에서부터 채워지고, 덜어 내면 뒤가 당겨 붙는다.
//                 함대 짐칸(용량 · 중량)은 함대 전체가 나눠 쓰므로 이 한 벌이면 맞는다.
//                 ★ 빈 칸 판정의 게임 규칙(0x4B5730) = `종류 != -1 && 갯수 > 0`.
//                   원산지도 넷째 칸도 안 본다.
//                 각 칸의 뜻도 소비처로 증명됐다 — +0x00 종류(0x415010 이 0x58BAB0 색인으로 쓴다),
//                 +0x04 갯수(0x4158AE), +0x08 원산지 도시 id(매각창 0열이 이름 생성기에 넘긴다).
//   소지금        모듈 + 0x1B6194
//   함선          모듈 + 0x1A4E18 + i*0x6C  (16척. ce/CDS_95.CT "1~16번 함선")
//     +0x00 이름  +0x28 함선종류(0~7)  +0x2C 배기본  +0x30 정원(최저승원)  +0x34 현재승원
//     +0x38·+0x3C 추진력 현재/최대  +0x40 중량  +0x44 용량(갯수)
//     +0x48·+0x4C 내구도 현재/최대  +0x50·+0x54 대포수 현재/최대
//     +0x58 대포종류  +0x5C 선수상(없으면 -1)  +0x60 함대 편입
//     ★ 세이브 파일의 함선 레코드(93바이트, 1함대 0x49B9~)와 열 순서가 같다 —
//       배종류·배기본·선원수·추진력(현재/최대)·최대중량·최대용량·내구도(현재/최대)·
//       대포수(현재/최대)·대포종류·선수상. 메모리에는 그 사이에 정원(+0x30)이 하나 더 있다.
//       살아 있는 값으로 대조: 대포가 0문인 배만 +0x58 이 -1 이고 나머지는 0·1·2 로 갈린다.
//     빈 칸은 최대내구도가 0 이다. 짐칸은 +0x44 "용량(갯수)" 합으로 본다 —
//     교역품이 갯수로 세는 값이라 짐(갯수 합)과 바로 견줄 수 있다.
//
// 단가 = 게임 함수 0x480890 이 준 값 x 3 / 2. 그 함수가 지역 기준가 · 도시 특산가 ·
// 품목 분류 보정 · 항로 발견 뒤 지난 날수 · 그리고 시세까지 다 반영해서 돌려준다.
//   ★ 시세를 밖에서 또 곱하면 안 된다 — marketdb.c 의 Mkt_SellPrice 주석에 대조표가 있다.
//   · 공통품은 지역 기준가 표에서 (0x42E3C0 이 그렇게 읽는다)
//   · 도시 특산품과 수입품은 그 도시 struct 의 +0x14 에서 (0x480E2F 가 그 값을 넘긴다)

